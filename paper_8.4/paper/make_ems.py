#!/usr/bin/env python3
"""Build LISFLOOD_8.4_EMS.tex (Elsevier elsarticle, Environmental Modelling &
Software) from the Copernicus source LISFLOOD_8.4.tex. Body text is copied
unchanged; only the class, front matter, back matter and three wide tables
differ. Run from paper/: python3 make_ems.py"""
import re, sys

src = open("LISFLOOD_8.4.tex").read()

# ---- body: from \introduction to the line before \codedataavailability
body = src[src.index("\\introduction"):src.index("\\codedataavailability")]
body = body.replace("\\introduction", "\\section{Introduction}\\label{sec:intro}", 1)
body = body.replace("\\conclusions", "\\section{Conclusions}\\label{sec:conclusions}", 1)

# wide tables -> \resizebox (same three as in the JAMES version)
for spec in ["\\begin{tabular}{@{}llrrrrrrr@{}}",
             "\\begin{tabular}{@{}ll rrrrr rrrrr r r@{}}",
             "\\begin{tabular}{@{}llrrrrrr@{}}",
             "\\begin{tabular}{@{}lccc@{}}",
             "\\begin{tabular}{@{}llrrrr@{}}",
             "\\begin{tabular}{@{}l rrrr rrrr rr@{}}"]:
    i = body.index(spec)
    j = body.index("\\end{tabular}", i) + len("\\end{tabular}")
    body = body[:i] + "\\resizebox{\\textwidth}{!}{%\n" + body[i:j] + "}" + body[j:]
# table footnote: left-aligned minipage instead of a centred line
body = body.replace(
    "\\\\[2pt]{\\footnotesize $^{a}$ HiPIMS writes no infiltration or water-balance output.}",
    "\\\\[2pt]\\begin{minipage}{\\textwidth}\\footnotesize $^{a}$ HiPIMS writes no infiltration or water-balance output.\\end{minipage}")

# Table 3: the two value columns are wide at 12 pt, which starved the X column
body = body.replace("\\centering\\small\n\\begin{tabularx}{\\textwidth}{@{}X ll@{}}",
                    "\\centering\\footnotesize\\setlength{\\tabcolsep}{4pt}\n\\begin{tabularx}{\\textwidth}{@{}>{\\raggedright\\arraybackslash}X >{\\raggedright\\arraybackslash}p{0.3\\textwidth} >{\\raggedright\\arraybackslash}p{0.3\\textwidth}@{}}")
assert "p{0.3\\textwidth}@{}}" in body
assert "Rehman2026lisflood83" not in body

# ---- abstract (EM&S limit: 150 words) ----
abstract = r"""LISFLOOD-FP 8.4 adds constant-rate, Green--Ampt and Horton infiltration and
evaporation to all seven CUDA solvers and to native Apple Metal FV1, FV2, DG2
and ACC, runs FV1, FV2 and DG2 on several GPUs, and makes CUDA FV1 and ACC
1.3--3.3 times faster than 8.3 with identical predictions. The losses match
analytical solutions within 1\,mm, FV1 is identical on one and four GPUs, and
on four FloodCastBench events the stored water ends within 4.4\,\% of the
references. For the July 2021 pluvial flood of the upper Alzette (4.7 million
cells), CUDA FV1, HiPIMS, SERGHEI-SWE and TRITON ran on the same inputs and
hardware; all overestimate the peaks without infiltration. Uncalibrated
Green--Ampt parameters from European soil databases raise the mean
Nash--Sutcliffe efficiency at four gauges from 0.12 to 0.66 (HiPIMS: 0.71);
Horton gives 0.64. CUDA FV1 is the fastest (33\,min on one A100); four GPUs
give a speed-up of 1.2--1.9."""
nw = len(re.sub(r"\\[,%]|[{}$]", " ", abstract).split())
print("abstract words:", nw)
assert nw <= 150, nw

